#!/usr/bin/env python3
"""Run the task suite with recovery ON and OFF and report real numbers.

Usage:
    python scripts/run_eval.py [--mode on|off|both]

Writes results/run_on.json / results/run_off.json (raw per-task results),
logs/run_on.jsonl / logs/run_off.jsonl (every failure + recovery), and
regenerates RESULTS.md from the JSON files. Env var
BROWSER_AGENT_RECOVERY=on|off sets the default mode.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from playwright.sync_api import sync_playwright  # noqa: E402

from src.agent import Agent, RunLog  # noqa: E402
from src.tasks import TASK_CATEGORIES, TASKS  # noqa: E402

FIXTURES = ROOT / "fixtures"
RESULTS = ROOT / "results"
LOGS = ROOT / "logs"


def run_mode(recovery: bool) -> dict:
    mode = "on" if recovery else "off"
    RESULTS.mkdir(exist_ok=True)
    LOGS.mkdir(exist_ok=True)
    log_path = LOGS / f"run_{mode}.jsonl"
    log_path.unlink(missing_ok=True)  # fresh log per run
    log = RunLog(str(log_path))
    rows = []
    with sync_playwright() as pw:
        browser = pw.chromium.launch(headless=True)
        for task in TASKS:
            context = browser.new_context()
            page = context.new_page()
            page.goto((FIXTURES / task.fixture).as_uri())
            agent = Agent(page, recovery=recovery, log=log)
            try:
                res = agent.run_task(task)
                row = {
                    "task": task.name,
                    "adversarial": task.adversarial,
                    "success": res.success,
                    "steps_completed": res.steps_completed,
                    "steps_total": len(task.steps),
                    "attempts": res.attempts,
                    "recoveries": res.recoveries,
                    "error": res.error,
                }
            except Exception as exc:  # harness-level failure: record, keep going
                row = {
                    "task": task.name,
                    "adversarial": task.adversarial,
                    "success": False,
                    "steps_completed": 0,
                    "steps_total": len(task.steps),
                    "attempts": 0,
                    "recoveries": 0,
                    "error": f"harness: {exc}",
                }
            rows.append(row)
            status = "PASS" if row["success"] else "FAIL"
            print(f"[{mode}] {status} {task.name} "
                  f"(attempts={row['attempts']}, recoveries={row['recoveries']})"
                  + (f" -- {row['error']}" if row["error"] else ""))
            context.close()
        browser.close()
    log.close()
    payload = {
        "mode": mode,
        "recovery": recovery,
        "ran_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "tasks": rows,
        "passed": sum(1 for r in rows if r["success"]),
        "total": len(rows),
    }
    (RESULTS / f"run_{mode}.json").write_text(json.dumps(payload, indent=2))
    return payload


def write_results_md() -> None:
    on_path, off_path = RESULTS / "run_on.json", RESULTS / "run_off.json"
    if not (on_path.exists() and off_path.exists()):
        print("RESULTS.md skipped: need both run_on.json and run_off.json")
        return
    on = json.loads(on_path.read_text())
    off = json.loads(off_path.read_text())
    off_by_task = {r["task"]: r for r in off["tasks"]}

    def pct(p: dict) -> str:
        return f"{p['passed']}/{p['total']} ({100.0 * p['passed'] / p['total']:.1f}%)"

    lines = [
        "# Evaluation results",
        "",
        "Generated by `scripts/run_eval.py` from `results/run_on.json` and "
        "`results/run_off.json`. Every number below comes from those files, "
        "which are the raw output of the runs — nothing is hand-entered.",
        "",
        "## Summary",
        "",
        f"- Recovery ON:  **{pct(on)}** tasks passed",
        f"- Recovery OFF: **{pct(off)}** tasks passed",
        "",
        "## By category",
        "",
        "| Category | Tasks | Recovery ON | Recovery OFF |",
        "|---|---|---|---|",
    ]
    cat_order: list[str] = []
    for r in on["tasks"]:
        cat = TASK_CATEGORIES.get(r["task"], "Other")
        if cat not in cat_order:
            cat_order.append(cat)
    for cat in cat_order:
        on_rows = [r for r in on["tasks"]
                   if TASK_CATEGORIES.get(r["task"], "Other") == cat]
        off_rows = [off_by_task[r["task"]] for r in on_rows]

        def cat_pct(rows: list) -> str:
            p = sum(1 for r in rows if r["success"])
            return f"{p}/{len(rows)} ({100.0 * p / len(rows):.1f}%)"
        lines.append(f"| {cat} | {len(on_rows)} "
                     f"| {cat_pct(on_rows)} | {cat_pct(off_rows)} |")
    lines += [
        "",
        "## Per-task results",
        "",
        "| Task | Adversarial | Recovery ON | Attempts (ON) | Recoveries used (ON) "
        "| Recovery OFF | Attempts (OFF) |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in on["tasks"]:
        o = off_by_task[r["task"]]

        def mark(x: dict) -> str:
            return "PASS" if x["success"] else "FAIL"
        lines.append(
            f"| {r['task']} | {'yes' if r['adversarial'] else 'no'} "
            f"| {mark(r)} | {r['attempts']} | {r['recoveries']} "
            f"| {mark(o)} | {o['attempts']} |")
    lines += ["", "## Failures", ""]
    any_fail = False
    for label, payload in (("ON", on), ("OFF", off)):
        for r in payload["tasks"]:
            if not r["success"]:
                any_fail = True
                lines.append(f"- [{label}] `{r['task']}`: {r['error']}")
    if not any_fail:
        lines.append("- none")
    lines.append("")
    (ROOT / "RESULTS.md").write_text("\n".join(lines))
    print("Wrote RESULTS.md")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=["on", "off", "both"],
                    default=os.environ.get("BROWSER_AGENT_RECOVERY", "both"))
    args = ap.parse_args()
    modes = {"on": [True], "off": [False], "both": [True, False]}[args.mode]
    for recovery in modes:
        run_mode(recovery)
    write_results_md()


if __name__ == "__main__":
    main()
